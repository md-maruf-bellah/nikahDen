export function getAdabForReligions(myReligion, partnerReligion) {
  if (!myReligion && !partnerReligion) {
    return RELIGIOUS_ADAB_DATA.Islam;
  }
  if (myReligion && partnerReligion && myReligion !== partnerReligion) {
    return RELIGIOUS_ADAB_DATA.CrossReligion;
  }
  const primary = partnerReligion || myReligion;
  if (primary && RELIGIOUS_ADAB_DATA[primary]) {
    return RELIGIOUS_ADAB_DATA[primary];
  }
  return RELIGIOUS_ADAB_DATA.Islam;
}

export function getReligionMeta(religion) {
  const r = String(religion || "").trim().toLowerCase();
  if (r.includes("islam") || r.includes("ইসলাম")) {
    return {
      name: "Islam",
      label: "ইসলাম",
      badgeClass: "bg-emerald-600/90 hover:bg-emerald-700 text-white border-emerald-700/80 shadow-sm backdrop-blur-sm",
      icon: "🌙",
    };
  }
  if (r.includes("hindu") || r.includes("সনাতন") || r.includes("হিন্দু")) {
    return {
      name: "Hinduism",
      label: "সনাতন",
      badgeClass: "bg-amber-600/90 hover:bg-amber-700 text-white border-amber-700/80 shadow-sm backdrop-blur-sm",
      icon: "🕉️",
    };
  }
  if (r.includes("christ") || r.includes("খ্রিস্ট")) {
    return {
      name: "Christianity",
      label: "খ্রিস্টান",
      badgeClass: "bg-sky-600/90 hover:bg-sky-700 text-white border-sky-700/80 shadow-sm backdrop-blur-sm",
      icon: "✝️",
    };
  }
  if (r.includes("buddh") || r.includes("বৌদ্ধ")) {
    return {
      name: "Buddhism",
      label: "বৌদ্ধ",
      badgeClass: "bg-yellow-600/90 hover:bg-yellow-700 text-white border-yellow-700/80 shadow-sm backdrop-blur-sm",
      icon: "☸️",
    };
  }
  return {
    name: religion || "Other",
    label: religion || "অন্যান্য",
    badgeClass: "bg-neutral-700/90 text-white border-neutral-600 shadow-sm backdrop-blur-sm",
    icon: "✨",
  };
}
